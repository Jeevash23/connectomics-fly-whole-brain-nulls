"""N3 without repeated pairs or self-loops ("N3s"), a post hoc check specified and frozen on 19 October 2026 before it ran.

The N3 family permutes postsynaptic ends within each block of connections that share a presynaptic and a postsynaptic
cell type. Because it is a permutation, a draw can join the same two neurons more than once (a repeated pair) or join a
neuron to itself (a self-loop). N3s takes N3 draw d exactly as generated by the frozen code and then removes every
repeated pair and self-loop by swapping the postsynaptic ends of two connections in the same block. A swap is accepted
only if neither new pair already exists and neither is a self-loop. Swaps within a block keep everything N3 keeps:
every connection keeps its presynaptic neuron, synapse count and sign, every neuron keeps its connections to and from
each cell type, and the block counts are unchanged. A block in which no simple arrangement is reached after the
repair attempts keeps its remaining repeated pairs, and their number is reported.

Repeated pairs can only arise within a block (both connections share a presynaptic and a postsynaptic neuron, hence
both cell types), so each block is repaired on its own with its own pair counts.
The repair is seeded by (3, 783, d, 1), so draw d of N3s is fixed.

Usage, from the code folder:
  python ../posthoc/n3_simple.py --check 0        build draw 0, check what it keeps, report repairs
  python ../posthoc/n3_simple.py --run 7 --out ../posthoc/n3s/v783/N3s_07
      run every experiment on draw 7 of N3s with the frozen run_wiring.py (30 trials, the published seeds)
"""
import json, sys
from collections import Counter
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path.cwd()))
import nulls
import wiring
from lif import Network

ORIGINAL_MAKE = nulls.make   # the frozen generator, kept even when run() wraps nulls.make
ATTEMPTS = 200          # random partners tried for each connection that needs a repair, before trying every partner
RESAMPLES = 20_000      # whole-block rearrangements tried for a block that single swaps could not make simple
SWEEPS = 50             # for a block still not simple: swap proposals per connection, starting from the measured block


def simple_n3(measured, draw):
    """Draw `draw` of N3, then repaired so that it has no repeated pairs and no self-loops."""
    net = ORIGINAL_MAKE('v783', measured, 'N3', draw)
    pre, post = net.pre.astype(np.int64), net.post.astype(np.int64).copy()
    cell_type, _, _ = nulls.labels_v783()
    t = int(cell_type.max()) + 1
    block = cell_type[pre] * t + cell_type[post]
    rng = np.random.default_rng([3, 783, int(draw), 1])
    key = pre * net.n + post
    _, inverse, counts = np.unique(key, return_inverse=True, return_counts=True)
    problem = (counts[inverse] > 1) | (pre == post)
    order = np.argsort(block, kind='stable')
    sorted_block = block[order]
    m_pre, m_post = measured.pre.astype(np.int64), measured.post.astype(np.int64)
    m_block = cell_type[m_pre] * t + cell_type[m_post]
    m_order = np.argsort(m_block, kind='stable')
    m_sorted_block = m_block[m_order]
    stats = Counter()
    for b in np.unique(block[problem]):                         # only blocks that hold a repeated pair or self-loop
        s, e = np.searchsorted(sorted_block, b, 'left'), np.searchsorted(sorted_block, b, 'right')
        idx = order[s:e]
        k = key[idx]
        stats['blocks_repaired'] += 1
        count = Counter(k.tolist())
        p, q = pre[idx].tolist(), post[idx].tolist()
        n = len(idx)

        def bad(i):
            return p[i] == q[i] or count[p[i] * net.n + q[i]] > 1

        todo = [i for i in range(n) if bad(i)]
        for i in todo:
            if not bad(i):
                continue
            partners = rng.integers(0, n, size=ATTEMPTS).tolist() + rng.permutation(n).tolist()
            for j in partners:
                if j == i or p[i] == q[j] or p[j] == q[i]:
                    continue
                ki_new, kj_new = p[i] * net.n + q[j], p[j] * net.n + q[i]
                if ki_new == kj_new or count[ki_new] > 0 or count[kj_new] > 0:
                    continue
                ki_old, kj_old = p[i] * net.n + q[i], p[j] * net.n + q[j]
                count[ki_old] -= 1
                count[kj_old] -= 1
                count[ki_new] += 1
                count[kj_new] += 1
                q[i], q[j] = q[j], q[i]
                stats['swaps'] += 1
                break
            else:
                stats['unrepaired_connections'] += 1
        if any(bad(i) for i in range(n)):
            # single swaps got stuck (small blocks): draw whole rearrangements of the block's postsynaptic ends until
            # one is simple; one always exists, because the measured arrangement is simple
            stats['blocks_resampled'] += 1
            for _ in range(RESAMPLES):
                cand = rng.permutation(q).tolist()
                keys = [a * net.n + b for a, b in zip(p, cand)]
                if len(set(keys)) == n and all(a != b for a, b in zip(p, cand)):
                    q = cand
                    stats['blocks_resampled_ok'] += 1
                    break
            else:
                # still stuck: start from the block's measured arrangement, which is simple, and randomise it with
                # swaps that keep it simple (SWEEPS accepted-or-rejected proposals per connection)
                # the measured block's partners of each presynaptic neuron (Network may store connections in its
                # own order, so the measured block is found by its cell types, not by connection index)
                s_m = np.searchsorted(m_sorted_block, b, 'left')
                e_m = np.searchsorted(m_sorted_block, b, 'right')
                partners_of = {}
                for a_, b_ in zip(m_pre[m_order[s_m:e_m]].tolist(), m_post[m_order[s_m:e_m]].tolist()):
                    partners_of.setdefault(a_, []).append(b_)
                q = [partners_of[a_].pop() for a_ in p]
                count = Counter(a * net.n + b for a, b in zip(p, q))
                for i, j in rng.integers(0, n, size=(SWEEPS * n, 2)).tolist():
                    if i == j or p[i] == q[j] or p[j] == q[i]:
                        continue
                    ki_new, kj_new = p[i] * net.n + q[j], p[j] * net.n + q[i]
                    if ki_new == kj_new or count[ki_new] > 0 or count[kj_new] > 0:
                        continue
                    count[p[i] * net.n + q[i]] -= 1
                    count[p[j] * net.n + q[j]] -= 1
                    count[ki_new] += 1
                    count[kj_new] += 1
                    q[i], q[j] = q[j], q[i]
                stats['blocks_from_measured'] += 1
        post[idx] = q
    out = Network(measured.n, pre, post, net.signed)
    out.ids, out.index = measured.ids, measured.index
    k2 = pre * net.n + post
    stats['repeated_pairs_left'] = int(k2.size - np.unique(k2).size)
    stats['self_loops_left'] = int((pre == post).sum())
    stats['connections_changed'] = int((post != net.post).sum())
    return out, net, dict(stats)


def check(draw):
    measured = wiring.load_v783()
    simple, n3, stats = simple_n3(measured, draw)
    c = nulls.check('v783', measured, simple, 'N3')
    c3 = nulls.check('v783', measured, n3, 'N3')
    cell_type, _, _ = nulls.labels_v783()
    t = int(cell_type.max()) + 1

    def profile(net):
        """Connections from each neuron to each cell type, and into each neuron from each cell type."""
        out_p = np.unique(net.pre.astype(np.int64) * t + cell_type[net.post], return_counts=True)
        in_p = np.unique(net.post.astype(np.int64) * t + cell_type[net.pre], return_counts=True)
        return out_p, in_p

    pm, ps = profile(measured), profile(simple)
    same_profiles = all(np.array_equal(a[0], b[0]) and np.array_equal(a[1], b[1]) for a, b in zip(pm, ps))
    report = {'draw': draw, 'repair': stats, 'n3s_check': c, 'n3_check': c3,
              'neuron_to_type_profiles_same': bool(same_profiles)}
    print(json.dumps(report, indent=1))
    return report


def run(draw, out):
    """Run every experiment on draw `draw` of N3s with the frozen run_wiring.py; the wiring is built inside the run."""
    held = {}

    def make(version, m, family, d):
        if family == 'N3' and d == draw:
            net, _, stats = simple_n3(m, d)
            held['stats'] = stats
            return net
        return ORIGINAL_MAKE(version, m, family, d)

    nulls.make = make
    import run_wiring
    sys.argv = ['run_wiring.py', '--version', 'v783', '--wiring', 'N3', '--draw', str(draw), '--out', out]
    if '--only' in ARGS:                      # a subset of experiments, for testing the plumbing only
        sys.argv += ['--only', ARGS[ARGS.index('--only') + 1]]
    run_wiring.main()
    run_path = Path(out) / 'run.json'
    if run_path.exists() and 'stats' in held:
        r = json.loads(run_path.read_text())
        r['family'] = 'N3s'
        r['repair'] = held['stats']
        run_path.write_text(json.dumps(r, indent=1))


ARGS = list(sys.argv)

if __name__ == '__main__':
    if sys.argv[1] == '--check':
        check(int(sys.argv[2]))
    elif sys.argv[1] == '--run':
        run(int(sys.argv[2]), sys.argv[sys.argv.index('--out') + 1])
