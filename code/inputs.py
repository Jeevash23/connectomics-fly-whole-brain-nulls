class _NoClasses(pickle.Unpickler):
    def find_class(self, module, name):
        raise pickle.UnpicklingError(f'class {module}.{name} not allowed')


def screen_types():
    """{cell type name: [v630 root IDs]} for the 106 screen cell types, read without allowing any class to load."""
    with open(REPO / 'sez_neurons.pickle', 'rb') as f:
        data = _NoClasses(f).load()
    return {str(k): [int(x) for x in v] for k, v in data.items()}
